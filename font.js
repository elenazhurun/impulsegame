  const ALIAS = { 'А': 'A', 'В': 'B', 'Е': 'E', 'К': 'K', 'М': 'M', 'Н': 'H', 'О': 'O', 'Р': 'P', 'С': 'C', 'Т': 'T', 'У': 'Y', 'Х': 'X', 'Ё': 'E' };

  const PIX = {};
  function pixels(ch) {
    if (PIX[ch]) return PIX[ch];
    let key = ch;
    if (ALIAS[key]) key = ALIAS[key];
    let rows = G[key];
    if (!rows) rows = G['?'];
    const list = [];
    rows.split('/').forEach((row, y) => {
      for (let x = 0; x < row.length; x++) if (row[x] === '#') list.push([x, y]);
    });
    PIX[ch] = list;
    return list;
  }

  function textWidth(str, scale) {
    return str.length * 6 * (scale || 1) - (scale || 1);
  }

  // opt: scale, shadow (цвет тени или null), align: 'left' | 'center' | 'right'
  function drawText(ctx, str, x, y, color, opt) {
    opt = opt || {};
    const s = opt.scale || 1;
    str = String(str).toUpperCase();
    if (opt.align === 'center') x = Math.round(x - textWidth(str, s) / 2);
    else if (opt.align === 'right') x = Math.round(x - textWidth(str, s));
    const shadow = opt.shadow === undefined ? '#000' : opt.shadow;
    const passes = shadow ? [[s, s, shadow], [0, 0, color]] : [[0, 0, color]];
    for (const [ox, oy, col] of passes) {
      ctx.fillStyle = col;
      let cx = x;
      for (const ch of str) {
        if (ch !== ' ') {
          const px = pixels(ch);
          for (let i = 0; i < px.length; i++) ctx.fillRect(cx + ox + px[i][0] * s, y + oy + px[i][1] * s, s, s);
        }
        cx += 6 * s;
      }
    }
  }

  window.PixFont = { drawText, textWidth };
